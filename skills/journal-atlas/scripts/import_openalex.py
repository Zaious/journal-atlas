# ---------- Data structures ----------


@dataclass
class JournalMetadata:
    """Structured metadata fetched from OpenAlex."""

    openalex_id: str
    display_name: str
    publisher: Optional[str]
    issn_print: Optional[str]
    issn_online: Optional[str]
    homepage_url: Optional[str]
    country_code: Optional[str]
    is_oa: bool
    apc_usd: Optional[int]
    h_index: Optional[int]
    two_year_citedness: Optional[float]
    i10_index: Optional[int]
    works_count: Optional[int]
    top_topics: list[dict]


# ---------- Fetching ----------


def fetch_by_issn(issn: str) -> JournalMetadata:
    """Fetch source data using an ISSN. ISSN format: XXXX-XXXX."""
    sources = Sources().filter(issn=issn).get()
    if not sources:
        raise ValueError(f"No journal found for ISSN {issn}")
    return _parse_source(sources[0])


def fetch_by_name(name: str) -> JournalMetadata:
    """Fetch source data using a display name search.

    Note: Display name search is fuzzy. The top result may not be correct.
    Always verify with --dry-run before writing files.
    """
    sources = Sources().search(name).get()
    if not sources:
        raise ValueError(f"No journal found for name '{name}'")
    return _parse_source(sources[0])


def fetch_by_id(openalex_id: str) -> JournalMetadata:
    """Fetch source data using an OpenAlex source ID. Format: S12345678."""
    source = Sources()[openalex_id]
    return _parse_source(source)


def _parse_source(source: dict) -> JournalMetadata:
    """Parse a raw OpenAlex source dict into our JournalMetadata structure."""
    issns = source.get("issn") or []
    stats = source.get("summary_stats") or {}
    topics = source.get("topics") or []

    return JournalMetadata(
        openalex_id=source.get("id", ""),
        display_name=source.get("display_name", ""),
        publisher=source.get("host_organization_name"),
        issn_print=issns[0] if len(issns) > 0 else None,
        issn_online=issns[1] if len(issns) > 1 else None,
        homepage_url=source.get("homepage_url"),
        country_code=source.get("country_code"),
        is_oa=bool(source.get("is_oa", False)),
        apc_usd=source.get("apc_usd"),
        h_index=stats.get("h_index"),
        two_year_citedness=stats.get("2yr_mean_citedness"),
        i10_index=stats.get("i10_index"),
        works_count=source.get("works_count"),
        top_topics=topics[:10],
    )


# ---------- Output rendering ----------



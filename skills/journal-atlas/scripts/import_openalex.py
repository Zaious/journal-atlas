# ---------- File naming ----------


def normalize_filename(display_name: str) -> str:
    """Convert journal name to lowercase-kebab-case filename.

    Examples:
        "Theory & Psychology" -> "theory-and-psychology"
        "The Journal of Personality" -> "journal-of-personality"
        "Phenomenology and the Cognitive Sciences" -> "phenomenology-and-the-cognitive-sciences"
    """
    name = display_name.strip()

    # Drop leading articles
    name = re.sub(r"^(The|A|An)\s+", "", name, flags=re.IGNORECASE)

    # Ampersand to "and"
    name = name.replace("&", "and")

    # Lowercase
    name = name.lower()

    # Replace colons, commas, dots with space
    name = re.sub(r"[:,.;]", " ", name)

    # Collapse spaces and convert to dash
    name = re.sub(r"\s+", "-", name.strip())

    # Strip non-alphanumeric (except dash)
    name = re.sub(r"[^a-z0-9-]", "", name)

    # Collapse multiple dashes
    name = re.sub(r"-+", "-", name).strip("-")

    return name


# ---------- CLI ----------


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Auto-populate a Journal Atlas entry from OpenAlex.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )

    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--issn", help="ISSN of the journal (e.g. 1234-5678)")
    group.add_argument("--name", help="Display name to search (fuzzy)")
    group.add_argument("--openalex-id", help="OpenAlex source ID (e.g. S12345678)")

    parser.add_argument(
        "--field",
        required=True,
        choices=["psychology", "hci", "qualitative-methods", "cognitive-science",
                 "multidisciplinary", "medical", "biology", "physics",
                 "conferences/hci", "conferences/ml", "conferences/nlp",
                 "conferences/data-mining"],
        help="Field directory under references/journals/",
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=Path("references/journals"),
        help="Base output directory (default: references/journals)",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print to stdout instead of writing a file",
    )

    args = parser.parse_args()

    try:
        if args.issn:
            meta = fetch_by_issn(args.issn)
        elif args.name:
            meta = fetch_by_name(args.name)
        else:
            meta = fetch_by_id(args.openalex_id)
    except Exception as exc:
        print(f"ERROR fetching from OpenAlex: {exc}", file=sys.stderr)
        return 1

    markdown = render_markdown(meta)

    if args.dry_run:
        print(markdown)
        return 0

    filename = normalize_filename(meta.display_name) + ".md"
    out_path = args.out_dir / args.field / filename

    if out_path.exists():
        print(
            f"ERROR: {out_path} already exists. "
            "Remove it manually or use --dry-run.",
            file=sys.stderr,
        )
        return 1

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(markdown, encoding="utf-8")
    print(f"Wrote: {out_path}")
    print()
    print("Next steps:")
    print(f"  1. Open {out_path} and fill in the *(fill manually)* fields")
    print("  2. Focus on Soft Metadata and Strategic Notes — those are the core value")
    print("  3. Run scripts/validate-structure.py (when available) before committing")
    return 0


if __name__ == "__main__":
    sys.exit(main())

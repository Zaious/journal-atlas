"""The committed topic vocabulary must match the corpus it is built from.

`topic_vocabulary.json` is the list of topic names the extraction stage may
match. It is generated by build_topic_vocabulary.py and committed, and twice it
was left stale after entries were added: on 2026-09-03 the live one was 42
names short, and on 2026-11-24 main was 155 names short (762 committed, 917 in
the corpus), which also made every deploy record a "-dirty" corpus version.
A query touching a missing name scores topic density against nothing, which
reads as a weak corpus rather than a stale file. The second time is a gate, not
a reminder (the maintainer's standing rule).

Fix a failure by running:  python demo/backend/build_topic_vocabulary.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import build_topic_vocabulary  # noqa: E402


def test_committed_vocabulary_matches_the_corpus():
    committed = json.loads(build_topic_vocabulary.OUTPUT_PATH.read_text(encoding="utf-8"))
    current = build_topic_vocabulary.collect_topics()
    missing = sorted(set(current) - set(committed))
    extra = sorted(set(committed) - set(current))
    assert not missing and not extra, (
        f"topic_vocabulary.json is stale: {len(missing)} topic(s) in the corpus are missing "
        f"(e.g. {missing[:3]}), {len(extra)} listed topic(s) no longer exist (e.g. {extra[:3]}). "
        "Run: python demo/backend/build_topic_vocabulary.py"
    )
    assert committed == current, "same topics but a different order: re-run build_topic_vocabulary.py"
